#!/usr/bin/env node
// The design tokens (ADR 0050), from their one source into the files for pages
// that have no Tailwind.
//
//   design/theme.css    the source: the tokens as Tailwind's theme, `@theme static`
//   design/tokens.css   the same tokens as plain CSS variables, for the landing,
//                       the walkthrough and the prototypes, which link it
//   keycloak/themes/tendero/login/resources/…
//                       the same tokens, the typefaces (design/fonts.css) and the
//                       shop's icon, copied into the sign-in page's theme: Keycloak
//                       serves a theme's own files only, so the page that signs a
//                       shopper in reads copies, written here and never by hand
//
//   node tools/tokens.mjs    rewrite them all; CI runs it and diffs them
//
// A browser does not know `@theme`, so the only change is that block becoming
// `:root`: the names, the values, the dark theme and the element rules are the
// source's, byte for byte. No dependencies: it runs on a fresh clone.

import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'design', 'theme.css'), 'utf8');

const blocks = source.match(/^@theme static \{$/gm) ?? [];
if (blocks.length !== 1) throw new Error(`design/theme.css must hold one \`@theme static {\` block; it holds ${blocks.length}.`);

const banner = `/* GENERATED by tools/tokens.mjs from design/theme.css — do not edit here.
   The tokens as plain CSS variables, for a page with no Tailwind. */

`;

const tokens = banner + source.replace(/^@theme static \{$/m, ':root {');
writeFileSync(join(root, 'design', 'tokens.css'), tokens);

// The sign-in page's theme (keycloak/themes/tendero): the same tokens, the same
// typefaces, the same icon as the shop's header.
const theme = join(root, 'keycloak', 'themes', 'tendero', 'login', 'resources');
writeFileSync(join(theme, 'css', 'tokens.css'), tokens);
copyFileSync(join(root, 'design', 'fonts.css'), join(theme, 'css', 'fonts.css'));
copyFileSync(join(root, 'frontend', 'apps', 'storefront', 'public', 'brand', 'tendero-icon-shop.svg'), join(theme, 'img', 'tendero-icon.svg'));

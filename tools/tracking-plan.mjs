#!/usr/bin/env node
// The tracking plan (ADR 0036), from its one source into the two places that read it.
//
//   docs/telemetry/tracking-plan.json   the source: features, their question and
//                                       decision, and every event and metric
//   docs/telemetry/tracking-plan.md     the plan for a person, with the audit's count
//   frontend/libs/shared/telemetry/src/lib/generated/tracked-events.ts
//                                       the browser's event types, so an event
//                                       nobody planned does not compile
//
//   node tools/tracking-plan.mjs        rewrite both; CI runs it and diffs them
//
// The plan's rules (a question and a decision on every feature, no id as an
// attribute, every signal claimed) and the code's agreement with it are checked by
// TrackingPlanTests, which runs with `dotnet test`. This only fails on a plan it
// cannot render. No dependencies: it runs on a fresh clone.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join('docs', 'telemetry', 'tracking-plan.json');
const plan = JSON.parse(readFileSync(join(root, source), 'utf8'));

const markdownPath = join(root, 'docs', 'telemetry', 'tracking-plan.md');
const typesPath = join(root, 'frontend', 'libs', 'shared', 'telemetry', 'src', 'lib', 'generated', 'tracked-events.ts');

const signals = new Map([...plan.events, ...plan.metrics].map((signal) => [signal.name, signal]));

for (const feature of plan.features) {
  for (const name of feature.signals) {
    if (!signals.has(name)) throw new Error(`${feature.name} names ${name}, which is not in the plan.`);
  }
}

// ---------------------------------------------------------------- the types

const tsType = (attribute) =>
  attribute.values ? attribute.values.map((value) => `'${value}'`).join(' | ') : attribute.type;

const claimedBy = (name) => plan.features.filter((feature) => feature.signals.includes(name));

function eventType(event) {
  const lines = ['  /**', `   * ${event.description}`];
  for (const feature of claimedBy(event.name)) {
    lines.push('   *', `   * ${feature.name}: ${feature.question}`, `   * Decides: ${feature.decision}`);
  }
  lines.push('   */', `  readonly ${event.name}: {`);
  for (const [name, attribute] of Object.entries(event.attributes)) {
    lines.push(`    /** ${attribute.description} */`, `    readonly ${name}: ${tsType(attribute)};`);
  }
  lines.push('  };');
  return lines.join('\n');
}

// A planned event is not in the types: it cannot be emitted until the plan says
// it is live, which is what makes "planned and emitted" impossible in the browser.
const liveEvents = plan.events.filter((event) => !event.planned);

const types = `// Generated by tools/tracking-plan.mjs from ${source.replaceAll('\\', '/')}.
// Do not edit: change the plan and run the script.

/**
 * Every event the frontends emit, by name, with its attributes (ADR 0036).
 *
 * An event that is not in the tracking plan does not compile. Each one carries
 * the question it answers and the decision its value would change.
 */
export interface TrackedEvents {
${liveEvents.map(eventType).join('\n\n')}
}

/**
 * Which events wait for analytics consent. A behavioural event says what a
 * person did and is dropped until they agree; a technical one is not.
 */
export const TRACKED_EVENT_CONSENT: Readonly<Record<keyof TrackedEvents, 'behavioural' | 'technical'>> = {
${liveEvents.map((event) => `  ${event.name}: '${event.consent}',`).join('\n')}
};
`;

// ---------------------------------------------------------------- the document

const cell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');
const status = (feature) => {
  if (feature.signals.length === 0) return 'none';
  return feature.signals.every((name) => !signals.get(name).planned) ? 'emitted' : 'planned';
};
const statusLabel = (feature) => {
  const value = status(feature);
  if (value !== 'planned') return value;
  const tasks = [...new Set(feature.signals.map((name) => signals.get(name).planned).filter(Boolean))];
  return `planned (${tasks.join(', ')})`;
};

const areas = [...new Set(plan.features.map((feature) => feature.area))];
const count = (value) => plan.features.filter((feature) => status(feature) === value).length;

function attributeRows(attributes) {
  const entries = Object.entries(attributes);
  if (entries.length === 0) return ['No attributes.'];
  return [
    '| Attribute | Type | Values | Meaning |',
    '|---|---|---|---|',
    ...entries.map(
      ([name, attribute]) =>
        `| \`${name}\` | ${attribute.type} | ${attribute.values ? attribute.values.map((v) => `\`${v}\``).join(', ') : '—'} | ${cell(attribute.description)} |`,
    ),
  ];
}

function signalSection(signal, kind) {
  const heading = `### \`${signal.name}\``;
  const facts =
    kind === 'metric'
      ? `${signal.instrument}, unit \`${signal.unit}\`${signal.planned ? ` · **planned, ${signal.planned}**` : ''}`
      : `browser event, ${signal.consent}${signal.planned ? ` · **planned, ${signal.planned}**` : ''}`;
  const answers = claimedBy(signal.name).map((feature) => `- **${feature.name}** — ${feature.question}`);
  return [heading, '', `${facts}. ${signal.description}`, '', 'Answers:', '', ...answers, '', ...attributeRows(signal.attributes)].join(
    '\n',
  );
}

const markdown = `# Tracking plan

<!-- Generated by tools/tracking-plan.mjs from ${source.replaceAll('\\', '/')}. Edit the JSON, then run the script. -->

Every feature answers one question: **which signal proves it is used, and that it
is worth it?** (ADR 0036). A signal enters this plan only with the decision its
value would change; a feature with no signal says why, here, instead of shipping
silent. \`TrackingPlanTests\` holds the code to the plan at both ends: every
metric a Tendero meter creates and every event the frontends emit is here, and
everything here that is not *planned* is emitted.

## The audit

${plan.features.length} features: **${count('emitted')}** answered by a signal emitted today,
**${count('planned')}** by a signal planned, and **${count('none')}** with no signal, each saying why.

${areas
  .map((area) =>
    [
      `### ${area[0].toUpperCase()}${area.slice(1)}`,
      '',
      '| Feature | Question | Decision it changes | Signals | Status |',
      '|---|---|---|---|---|',
      ...plan.features
        .filter((feature) => feature.area === area)
        .map(
          (feature) =>
            `| ${feature.name} | ${cell(feature.question)} | ${cell(feature.decision)} | ${
              feature.signals.length ? feature.signals.map((name) => `\`${name}\``).join(', ') : `— ${cell(feature.gap)}`
            } | ${statusLabel(feature)} |`,
        ),
    ].join('\n'),
  )
  .join('\n\n')}

## Events

Emitted in the browser through \`Telemetry.trackEvent\`, whose types are generated
from this plan (\`libs/shared/telemetry/src/lib/generated/tracked-events.ts\`). A
*behavioural* event is dropped until the shopper grants analytics consent; a
*technical* one is not.

${plan.events.map((event) => signalSection(event, 'event')).join('\n\n')}

## Metrics

Created by a Tendero \`Meter\` (\`TelemetrySources\`), as a static field. No
attribute identifies a person, a product or an order.

${plan.metrics.map((metric) => signalSection(metric, 'metric')).join('\n\n')}
`;

mkdirSync(dirname(typesPath), { recursive: true });
writeFileSync(typesPath, types);
writeFileSync(markdownPath, markdown);
console.log(`Tracking plan: ${plan.features.length} features, ${plan.events.length} event(s), ${plan.metrics.length} metric(s).`);
